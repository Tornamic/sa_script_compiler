// What a command argument accepts (tCommandInfo::aArgTypes), 0 ends the list
enum eArgType : uint8_t
{
    ARG_NONE,
    ARG_INT_CONST,         // number only
    ARG_FLOAT_CONST,
    ARG_VAR_INT,           // global variable only
    ARG_VAR_FLOAT,
    ARG_DECLARE_VAR_INT,   // name declared by VAR_INT
    ARG_DECLARE_VAR_FLOAT,
    ARG_LVAR_INT,          // local variable only
    ARG_LVAR_FLOAT,
    ARG_DECLARE_LVAR_INT,  // name declared by LVAR_INT
    ARG_DECLARE_LVAR_FLOAT,
    ARG_SCRIPT_PARAM,      // START_NEW_SCRIPT parameter, checked against the target's locals
    ARG_INT,               // number or variable
    ARG_FLOAT,
    ARG_RETURN_INT,        // variable written by the command
    ARG_RETURN_FLOAT,
    ARG_LABEL,
    ARG_NAME,        // compiled argument type only (CARG_NAME)
    ARG_TEXT_LABEL,  // 8 char text key, e.g. PRINT_NOW (AMMUA)
    ARG_VAR_TEXT_LABEL,
    ARG_LVAR_TEXT_LABEL,
    ARG_DECLARE_VAR_TEXT_LABEL,
    ARG_DECLARE_LVAR_TEXT_LABEL,
    ARG_STRING,        // quoted string, e.g. SAVE_STRING_TO_DEBUG_FILE "x = "
    ARG_TEXT_LABEL16,  // 16 char text, e.g. REQUEST_ANIMATION COP_AMBIENT
    ARG_VAR_TEXT_LABEL16,
    ARG_LVAR_TEXT_LABEL16,
    ARG_DECLARE_VAR_TEXT_LABEL16,
    ARG_DECLARE_LVAR_TEXT_LABEL16,
    ARG_UNKNOWN,  // compiled argument type only (CARG_INVALID)
};

